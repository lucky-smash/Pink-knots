// Generates the ribbon-knot outline used for the engraved background motif.
// The shape follows the infinity ribbon in the original Pink Knots logo: a lemniscate
// whose band is wide on the top-left → bottom-right diagonal (drawn over the crossing)
// and thin on the other, which reads as a twisting ribbon.
// Writes src/components/knotPaths.ts. Re-run after tuning the constants below.
import { writeFileSync } from "node:fs";

const W = 1000;
const H = 600;
const A = 450; // half-width of the lemniscate
const Y_STRETCH = 1.5; // the logo's loops are taller than a true lemniscate
const TILT = (-9 * Math.PI) / 180; // right loop sits higher, as in the logo
const W_MIN = 9;
const W_MAX = 74;
const STEPS = 220;
const PAD = 16; // viewBox margin around the ribbon

// Under strand skips ±UNDER_GAP around the crossing; over strand covers ±OVER_SPAN.
const UNDER_GAP = 0.3;
const OVER_SPAN = 0.42;
// Short piece of the over strand used to cut a gap where it crosses the under strand.
const CUT_SPAN = 0.16;

function centre(t) {
  const d = 1 + Math.sin(t) ** 2;
  const x = (A * Math.cos(t)) / d;
  const y = (Y_STRETCH * A * Math.sin(t) * Math.cos(t)) / d;
  return [W / 2 + x * Math.cos(TILT) - y * Math.sin(TILT), H / 2 + x * Math.sin(TILT) + y * Math.cos(TILT)];
}

const width = (t) => W_MIN + (W_MAX - W_MIN) * ((1 + Math.sin(t)) / 2) ** 1.7;

function ribbon(t0, t1) {
  const n = Math.max(8, Math.round((STEPS * (t1 - t0)) / (2 * Math.PI)));
  const left = [];
  const right = [];
  for (let i = 0; i <= n; i++) {
    const t = t0 + ((t1 - t0) * i) / n;
    const [x, y] = centre(t);
    const [xa, ya] = centre(t - 1e-4);
    const [xb, yb] = centre(t + 1e-4);
    const len = Math.hypot(xb - xa, yb - ya);
    const nx = -(yb - ya) / len;
    const ny = (xb - xa) / len;
    const h = width(t) / 2;
    left.push([x + nx * h, y + ny * h]);
    right.push([x - nx * h, y - ny * h]);
  }
  return [...left, ...right.reverse()];
}

const mid = Math.PI / 2;
const under = ribbon(mid + UNDER_GAP, mid + 2 * Math.PI - UNDER_GAP);
const over = ribbon(mid - OVER_SPAN, mid + OVER_SPAN);
const cut = ribbon(mid - CUT_SPAN, mid + CUT_SPAN);

// Fit the viewBox to the ribbon (the tilted, stretched loops overflow the nominal W × H),
// with room for the engraving's shadow and highlight offsets so nothing gets sliced off.
const all = [...under, ...over];
const minX = Math.min(...all.map((p) => p[0])) - PAD;
const minY = Math.min(...all.map((p) => p[1])) - PAD;
const vw = Math.ceil(Math.max(...all.map((p) => p[0])) + PAD - minX);
const vh = Math.ceil(Math.max(...all.map((p) => p[1])) + PAD - minY);
const d = (pts) => "M" + pts.map(([x, y]) => `${(x - minX).toFixed(1)} ${(y - minY).toFixed(1)}`).join("L") + "Z";

const out = `// Generated by scripts/generate-knot.mjs — do not edit by hand.
export const KNOT_VIEWBOX = "0 0 ${vw} ${vh}";
export const KNOT_UNDER = "${d(under)}";
export const KNOT_OVER = "${d(over)}";
export const KNOT_CUT = "${d(cut)}";
`;
writeFileSync(new URL("../src/components/knotPaths.ts", import.meta.url), out);
console.log(`knotPaths.ts written (${out.length} bytes)`);
